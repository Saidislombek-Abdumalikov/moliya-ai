import assert from 'node:assert/strict';
import {createPauseDetector,prepareSilenceMonitor} from '../src/voiceSilence';
const quiet=createPauseDetector();
assert.equal(quiet(0,0,true),false);
assert.equal(quiet(0,30000,true),false,'Never send initial silence');
const pause=createPauseDetector();
for(const at of [0,50,100,150,200,250])assert.equal(pause(0.06,at,true),false);
assert.equal(pause(0,1249,true),false);
assert.equal(pause(0,1250,true),true,'Send after 1s following speech');
assert.equal(pause(0,2000,true),false,'Send once');
const manual=createPauseDetector();
for(const at of [0,100,200])manual(0.1,at,true);
assert.equal(manual(0,300,false),false);
assert.equal(manual(0,3000,false),false,'Manual mode never auto-sends');
assert.equal(manual(0,4000,true),false,'Enabling requires fresh speech');
const click=createPauseDetector();
click(0.2,0,true);click(0.2,50,true);
assert.equal(click(0,1200,true),false,'A brief click does not arm sending');
const resumed=createPauseDetector();
for(const at of [0,100,200])resumed(0.1,at,true);
assert.equal(resumed(0,900,true),false);
resumed(0.1,950,true);
assert.equal(resumed(0,1800,true),false,'Continued speech resets silence');
assert.equal(resumed(0,1950,true),true);
// Missing Web Audio leaves the manual button usable instead of failing recording.
const monitor=prepareSilenceMonitor();
assert.equal(monitor.start({} as MediaStream,()=>true,()=>assert.fail('must not send')),false);
monitor.stop();monitor.stop();
console.log('Voice silence: initial silence, one-second pause, one send, manual mode, brief noise, resumed speech and unsupported analyser fallback passed. No real microphone test.');
